-----------------------------------------------------------------------
-- Gitsigns
--
-- Displays Git change indicators and provides Git hunk operations.
-----------------------------------------------------------------------

local ok, gitsigns = pcall(require, "gitsigns")

if not ok then
    return
end

-----------------------------------------------------------------------
-- Setup
-----------------------------------------------------------------------

gitsigns.setup({
    -------------------------------------------------------------------
    -- Signs
    -------------------------------------------------------------------

    signs = {
        add          = { text = "│" },
        change       = { text = "│" },
        delete       = { text = "_" },
        topdelete    = { text = "‾" },
        changedelete = { text = "~" },
    },

    signcolumn = true,
    numhl = false,
    linehl = false,
    word_diff = false,

    -------------------------------------------------------------------
    -- Blame
    -------------------------------------------------------------------
    current_line_blame = true,

    current_line_blame_opts = {
        delay = 500,
    },

    -------------------------------------------------------------------
    -- Preview
    -------------------------------------------------------------------
    preview_config = {
        border = "rounded",
        style = "minimal",
    },

    -------------------------------------------------------------------
    -- Buffer Attach
    -------------------------------------------------------------------
})
